# Database
# ============================================================
# Si DATABASE_URL existe → PostgreSQL (producción/Render)
# Si no existe → SQLite (desarrollo local)
# Usamos dj_database_url.parse() en lugar de config() para
# parsear directamente el valor sin releer el entorno.
# ============================================================

DATABASE_URL = os.environ.get('DATABASE_URL', '').strip()

# Debug: confirmar en logs de Render qué URL se está usando
print(f"[DB CONFIG] IS_RENDER={IS_RENDER} IS_RAILWAY={IS_RAILWAY} | DATABASE_URL presente={bool(DATABASE_URL)}", file=sys.stderr, flush=True)
if DATABASE_URL and '@' in DATABASE_URL:
    _host = DATABASE_URL.split('@')[-1].split('/')[0]
    print(f"[DB CONFIG] DB host={_host}", file=sys.stderr, flush=True)

if DATABASE_URL:
    # Forzar SSL para Supabase (pooler session requiere SSL)
    _db_url = DATABASE_URL
    if 'sslmode' not in _db_url and 'supabase.com' in _db_url:
        _db_url += '?' if '?' not in _db_url else '&'
        _db_url += 'sslmode=require'

    DATABASES = {
        'default': dj_database_url.parse(
            _db_url,
            conn_max_age=600,
            conn_health_checks=True,
        )
    }
else:
    # Desarrollo local — usar SQLite (no requiere PostgreSQL corriendo)
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


